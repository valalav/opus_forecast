# Поправки на перенос тарифа для 2027: модели обучены на выборке, где
# индексация приходится на июль. Если новый график (октябрь) сохраняется,
# июльскую тарифную компоненту надо снять, октябрьскую — добавить.
JKH_JULY_HISTORIC_PCT = 3.175   # среднее по июлям 2016-2025
JKH_OCT_2027_PCT = 6.0          # предполагаемая индексация октября 2027
ADJ_JUL_2027 = -JKH_JULY_HISTORIC_PCT * W_JKH
ADJ_OCT_2027 = +JKH_OCT_2027_PCT * W_JKH

# Сценарные сдвиги на 2027, п.п. в месяц
SCEN_LOW_SHIFT = -0.18
SCEN_HIGH_SHIFT = +0.20


def load_actuals() -> pd.Series:
    m = pd.read_csv(ROOT / "data" / "inflation_data.csv", sep=";", decimal=",", encoding="utf-8-sig")
    m.columns = [c.strip() for c in m.columns]
    m["per"] = pd.to_datetime(m["Date"], format="%d.%m.%Y").dt.to_period("M")
    return pd.to_numeric(m.set_index("per")["mom"], errors="coerce") - 100.0


def load_models() -> pd.DataFrame:
    path = ROOT / "data" / "precomputed_forecasts_h17.json"
    raw = json.load(open(path, encoding="utf-8"))
    dates = [str(d)[:7] for d in raw["forecast_dates"]]
    cols = {k: v for k, v in raw["forecasts"].items() if isinstance(v, list) and len(v) == len(dates)}
    return pd.DataFrame(cols, index=dates)


def build_forecast(models: pd.DataFrame, actual: pd.Series) -> pd.DataFrame:
    ens = models["Ensemble"]
    rows = []
    for per in models.index:
        if per in DECIDED_2026:
            c, lo, hi, note = DECIDED_2026[per]
            src = "Экспертная точка (nowcast + факторы)"
        else:
            c = float(ens[per])
            note = "Ensemble моделей"
            if per == "2027-07":
                c += ADJ_JUL_2027
                note = f"Ensemble {ens[per]:+.2f} минус июльский тариф ({ADJ_JUL_2027:+.2f} пп)"
            elif per == "2027-10":
                c += ADJ_OCT_2027
                note = f"Ensemble {ens[per]:+.2f} плюс индексация ЖКХ ({ADJ_OCT_2027:+.2f} пп)"
            lo, hi = c + SCEN_LOW_SHIFT, c + SCEN_HIGH_SHIFT
            src = "Модельный ансамбль + поправка на график тарифов"
        rows.append(dict(Месяц=per, MoM_центр=round(c, 2), MoM_низкий=round(lo, 2),
                         MoM_высокий=round(hi, 2), Источник=src, Комментарий=note))
    df = pd.DataFrame(rows)

    # Индекс и YoY считаем по сцепке факта и прогноза.
    path = pd.concat([actual, pd.Series(df.set_index("Месяц")["MoM_центр"].values,
                                        index=pd.PeriodIndex(df["Месяц"], freq="M"))])
    path = path[~path.index.duplicated(keep="last")].sort_index()
    lvl = (1 + path / 100).cumprod()
    yoy = (lvl / lvl.shift(12) - 1) * 100
    df["Индекс_MoM"] = (100 + df["MoM_центр"]).round(2)
    df["Инфляция_год_к_году_%"] = [round(float(yoy.get(pd.Period(p, "M"), np.nan)), 2) for p in df["Месяц"]]
    return df


def annual_table(df: pd.DataFrame, actual: pd.Series) -> pd.DataFrame:
    rows = []
    for y in [2022, 2023, 2024, 2025]:
        s = actual.loc[f"{y}-01":f"{y}-12"]
        rows.append(dict(Год=y, Тип="факт", Инфляция_декабрь_к_декабрю=round(((1 + s / 100).prod() - 1) * 100, 2)))
    s26a = actual.loc["2026-01":"2026-07"]
    f26 = df[df["Месяц"].str.startswith("2026")]
    tot26 = ((1 + s26a / 100).prod() * (1 + f26["MoM_центр"] / 100).prod() - 1) * 100
    lo26 = ((1 + s26a / 100).prod() * (1 + f26["MoM_низкий"] / 100).prod() - 1) * 100
    hi26 = ((1 + s26a / 100).prod() * (1 + f26["MoM_высокий"] / 100).prod() - 1) * 100
    rows.append(dict(Год=2026, Тип="факт 7 мес + прогноз 5 мес",
                     Инфляция_декабрь_к_декабрю=round(tot26, 2),
                     Низкий=round(lo26, 2), Высокий=round(hi26, 2)))
    f27 = df[df["Месяц"].str.startswith("2027")]
    rows.append(dict(Год=2027, Тип="прогноз",
                     Инфляция_декабрь_к_декабрю=round(((1 + f27["MoM_центр"] / 100).prod() - 1) * 100, 2),
                     Низкий=round(((1 + f27["MoM_низкий"] / 100).prod() - 1) * 100, 2),
                     Высокий=round(((1 + f27["MoM_высокий"] / 100).prod() - 1) * 100, 2)))
    return pd.DataFrame(rows)


